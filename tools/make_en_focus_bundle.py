#!/usr/bin/env python3
"""
Пересобирает английский бандл переводов фокусов game/languages/focus/Bundle.properties.

Русский бандл хранит английские тексты рядом с русскими в ключах с суффиксом
_EN (BE2_F_GER_MOB = Мобилизационный декрет / BE2_F_GER_MOB_EN = Mobilization
Decree). Этот скрипт собирает из них чистый английский бандл: ключ BE2_F_GER_MOB
= Mobilization Decree. Ключи без _EN-пары копируются как есть.

Ключи не обязаны начинаться с BE2_: подписи эффектов фокусов (ModAttack,
FocusMoney, Turns) названы обычными словами.

  usage: make_en_focus_bundle.py <каталог game/languages/focus>
"""
import io
import os
import re
import sys


def main():
    base = sys.argv[1]
    ru_path = os.path.join(base, 'Bundle_ru.properties')
    en_path = os.path.join(base, 'Bundle.properties')
    with io.open(ru_path, 'r', encoding='utf-8', newline='') as fh:
        ru = fh.read()

    pairs = {}
    order = []
    for m in re.finditer(r'^([A-Za-z][A-Za-z0-9_]*)\s*=\s*(.*?)(?=\r?\n)', ru, re.M):
        key, val = m.group(1), m.group(2).rstrip()
        if key.endswith('_EN'):
            base_key = key[:-3]
            if base_key not in pairs:
                order.append(base_key)
            pairs[base_key] = val
        else:
            if key not in pairs:
                order.append(key)
            pairs.setdefault(key, val)

    lines = [
        '# Age of Civilizations II - national focus trees (EN)',
        '# Generated by _focus_port/tools/make_en_focus_bundle.py',
        '# Russian texts live in Bundle_ru.properties, English ones in *_EN keys.',
        '',
    ]
    for key in order:
        lines.append('%s = %s ' % (key, pairs[key]))
    out = '\r\n'.join(lines) + '\r\n'
    with io.open(en_path, 'w', encoding='utf-8', newline='') as fh:
        fh.write(out)
    print('    %s: ключей %d' % (os.path.basename(en_path), len(order)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
